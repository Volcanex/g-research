#!/usr/bin/env python3
"""Turn a sweep's rows into thesis literature records.

  sweeps.py picks terms.txt SWEEP.txt > picks/N-name.txt    reading the sweep ranked 2 or 3, for shelve.py
  sweeps.py tools terms.txt SWEEP.txt... > tools.toml       code, tools and data the sweeps ranked 2 or 3

A sweep is a research job's report, kept beside the other reports. Its rows are tab separated:
rank (0 to 3), NEW or KNOWN, kind, year, who, title, address, how far it was read, note.
Every row stays in the sweep file, including what was turned down. Ranks 2 and 3 move on, and
so does a lower row named in raised.txt, which says why it was raised."""
import argparse, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import DATA

CODE = ('repo', 'tool', 'dataset', 'crate', 'library', 'lib', 'code')
LICENCE = re.compile(r'\b(MIT|Apache(?:-2\.0)?|BSD-\d|L?GPL-\d\+?|CC0|CC BY(?:-[A-Z]+)*(?: \d\.\d)?|zlib|MPL-2\.0|ISC|Unlicense|public[- ]domain|proprietary EULA|custom licen[cs]e)\b')


RAISED = [(a.strip().lower(), b.strip()) for a, b in
          (l.split('|', 1) for l in open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'raised.txt')) if '|' in l and not l.startswith('#'))]


def rows(path):
    name = re.sub(r'-\d{4}-\d\d-\d\d\.txt$', '', path.rsplit('/', 1)[-1]).replace('-', ' ', 2)
    for line in open(path, errors='replace'):
        c = [x.strip() for x in line.rstrip('\n').split('\t')]
        if len(c) < 9 or c[0] not in '0123' or c[1] not in ('NEW', 'KNOWN') or not c[6].startswith('http'):
            continue
        why = next((b for a, b in RAISED if a in c[5].lower()), None)
        if c[0] in ('2', '3'):
            yield name + ', ranked ' + c[0], c
        elif why:
            c[8] = why + '. The sweep said: ' + c[8]
            yield name + ', ranked ' + c[0] + ' and raised by hand', c


def plain(note):
    """One sentence per clause."""
    parts = [p.strip() for p in note.replace('|', '/').split('\x3b') if p.strip()]
    return '. '.join(p[0].upper() + p[1:] for p in parts).rstrip('.') + '.'


def part_of(title, note, terms):
    return next((a for a, rx in terms if rx.search(title)), None) or next((a for a, rx in terms if rx.search(note)), 'general')


def q(s):
    return '"' + str(s).replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('mode', choices=['picks', 'tools'])
    parser.add_argument('terms', nargs='?', default=os.path.join(os.path.dirname(__file__), 'terms.txt'))
    parser.add_argument('sweeps', nargs='*', help='defaults to G_RESEARCH_DATA/sweeps/*.txt')
    args = parser.parse_args()
    paths = args.sweeps or sorted(__import__('glob').glob(os.path.join(DATA, 'sweeps', '*.txt')))
    if not paths:
        parser.error('no sweep files found')
    mode, terms = args.mode, [(a.strip(), re.compile(b.strip(), re.I)) for a, b in
                             (l.split('|', 1) for l in open(args.terms) if '|' in l and not l.startswith('#'))]
    if mode == 'picks':
        for path in paths:
            for name, c in rows(path):
                if c[1] == 'NEW' and c[2] not in CODE:
                    title = c[5].replace('|', '/')
                    print(' | '.join([part_of(title, c[8], terms), title, plain(c[8]), c[6].split()[0], name,
                                      c[4].replace('|', '/'), c[3], c[2] if c[2] in ('paper', 'talk') else 'page']))
        return
    print('# Generated by sweeps.py from the sweeps kept beside the reports. Code, tools and data that')
    print('# could help: a slow exact reference to check a cheap rule against, a bake tool, a measured')
    print('# data set, or a library to use. Nothing here is adopted. part says what it would serve.')
    seen = set()
    for path in paths:
        for name, c in rows(path):
            if c[2] not in CODE:
                continue
            short = re.split(r':| \(| \u2014 ', c[5])[0].strip()
            tid = 't.' + re.sub(r'[^a-z0-9]+', '-', short.lower()).strip('-')[:40]
            if tid in seen or c[6] in seen:
                continue
            seen.update((tid, c[6]))
            gates = sorted(set(re.findall(r'\bg\.[a-z0-9]+\.[a-z0-9-]+', c[8])))
            lic = LICENCE.search(c[8])
            print(f'\n[[tool]]\nid = {q(tid)}\nstatus = "candidate"\nname = {q(c[5])}\nwho = {q(c[4])}\nform = {q(c[2])}\nurl = {q(c[6])}')
            print(f'licence = {q(lic.group(1) if lic else "not read")}\nrank = {c[0]}\npart = {q(part_of(c[5], c[8], terms))}')
            if gates:
                print('protects = [' + ', '.join(q(g) for g in gates) + ']')
            print(f'found_by = {q(name)}\nuse = {q(plain(c[8]))}')


if __name__ == '__main__':
    main()
