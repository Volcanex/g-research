#!/usr/bin/env python3
"""Write shelf.toml: what the wider sweeps turned up that is worth holding and nobody has read.

  shelve.py PICKS... [--papers papers.toml] [--tables TABLE[,TABLE...]] > shelf.toml

A picks file has one find per line: part | title | why, then optionally | address | found by |
authors | year. A line with no address is looked up by title in the tables neighbours.py wrote,
which give its address and year and say which sweep found it. Any other links the venue
list gave for it are kept as also, for the fetcher to try. The existing bibliography and the piece Sources seed the known set at runtime.
A known find is left out and named on stderr. The bibliography is never copied.
A find with no address anywhere is a fault: exit 1."""
import argparse, difflib, os, re, sys, tomllib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import known, norm, urlkey


def q(s):
    return '"' + str(s).replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('picks', nargs='+')
    parser.add_argument('--papers', help='additional known papers.toml')
    parser.add_argument('--tables', default='', help='comma separated neighbours tables')
    parser.add_argument('--hold-known', action='store_true', help='shelve finds already in the bibliography, which lists them without holding them')
    args = parser.parse_args()
    titles, urls = known()
    if args.papers:
        papers = tomllib.load(open(args.papers, 'rb')).get('paper', [])
        titles += [p['title'] for p in papers]
        urls.update(urlkey(p.get('url', '')) for p in papers)
    ours = [norm(t) for t in titles]
    walked = []  # rows of title, address, year, who found it
    for path in filter(None, args.tables.split(',')):
        rows = [l.rstrip('\n').split('\t') for l in open(path, errors='replace')]
        head, rows = rows[0], rows[1:]
        if head[0] == 'parts touched':
            walked += [(r[4], r[5], r[2], f'venue walk, {r[3]} {r[2]}', (r + [''])[6].split()) for r in rows]
        elif head[0] == 'hits':
            walked += [(r[3], r[5], r[1], 'keyword sweep, ' + r[7].split(' \x3b ')[0], []) for r in rows]
        else:
            walked += [(r[2], r[4], r[1], f'cited by {r[0]} of the papers we hold', []) for r in rows]
    seen, have, where, bad = set(), set(), {}, 0
    print('# Generated by shelve.py from the picks kept beside the reports. Finds from the wider sweeps,')
    print('# unread until a reading job has checked them. A known title or address is left out.')
    for path in args.picks:
        for line in open(path):
            if not line.strip() or line.startswith('#'):
                continue
            c = [x.strip() for x in line.rstrip('\n').split('|')] + [''] * 8
            part, title, why, url, by, authors, year, form = c[:8]
            also = []
            hit = next((r for r in walked if norm(title) == norm(r[0]) and (r[1] or r[4])), None) or \
                next((r for r in walked if norm(title) in norm(r[0]) and (r[1] or r[4])), None)
            if hit:
                also = [a for a in hit[4] if a != (url or hit[1])]
            if not url:
                if hit:
                    full = re.sub(r'\s*(-->|\([^)]*\))\s*', ' ', hit[0]).strip()
                    title, url, year, by = (full if len(full) > len(title) else title), hit[1], hit[2], by or hit[3]
            n = norm(title)
            if not args.hold_known and (urlkey(url) in urls or any(n == o or (len(n) > 24 and difflib.SequenceMatcher(None, n, o).ratio() > 0.92) for o in ours)):
                print('already known:', title, file=sys.stderr)
                continue
            # the same address from another picks file is the same find under another title.
            # Within one file a shared address is a listing page that several finds sit on.
            if n in have or (url and where.get(url, path) != path):
                print('picked twice:', title, file=sys.stderr)
                continue
            have.add(n)
            where.setdefault(url, path)
            if not url:
                print('NO ADDRESS:', title, file=sys.stderr)
                bad += 1
                continue
            words = [w for w in re.findall(r'[a-z]+', title.lower()) if len(w) > 3 and w not in ('with', 'from', 'that', 'this', 'using')]
            base = 's.' + (re.sub(r'[^a-z]', '', (authors.split('\x3b')[0].split(',')[0].split() or ['x'])[-1].lower()) or 'x' if authors else 'v') + str(year) + '-' + '-'.join(words[:2])
            sid, i = base, 2
            while sid in seen:
                sid, i = f'{base}{i}', i + 1
            seen.add(sid)
            print(f'\n[[shelf]]\nid = {q(sid)}\nstatus = "unread"\ntitle = {q(title)}')
            if authors:
                print(f'authors = {q(authors)}')
            if year:
                print(f'year = {q(year)}')
            print(f'form = {q(form or "paper")}\nurl = {q(url)}\npart = {q(part)}\nfound_by = {q(by)}\nwhy = {q(why)}')
            if also:
                print('also = [' + ', '.join(q(a) for a in also) + ']')
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
